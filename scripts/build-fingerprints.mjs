// Measures every instrument of the app (src/audio/instruments.js) the same way the audio
// analysis measures a recording, and writes src/analysis/fingerprints.js.
// Needs Chromium (Playwright): the instruments are Web Audio patches, so they are rendered
// by a real OfflineAudioContext. Run again whenever an instrument changes:
//   node scripts/build-fingerprints.mjs          write the file
//   node scripts/build-fingerprints.mjs --check  fail if the file is out of date
import { writeFile, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/analysis/fingerprints.js');
const PORT = 5199;
const { chromium } = await import('playwright').catch(() => import('/opt/node22/lib/node_modules/playwright/index.mjs'));

const server = spawn('node', [resolve(ROOT, 'scripts/serve.mjs'), String(PORT)], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
let rows;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined, args: ['--autoplay-policy=no-user-gesture-required'] }).catch(() => chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }));
try {
  const page = await browser.newPage();
  await page.goto(`http://localhost:${PORT}/index.html`, { waitUntil: 'domcontentloaded' });
  rows = await page.evaluate(async () => {
    const { AudioEngine } = await import('/src/audio/engine.js');
    const { INSTRUMENTS } = await import('/src/audio/instruments.js');
    const { defaultState } = await import('/src/state.js');
    const { describeTimbre } = await import('/src/analysis/timbre.js');
    const { trackPitch } = await import('/src/analysis/pitch.js');
    const { segmentNotes } = await import('/src/analysis/notes.js');
    const settings = defaultState().audio;
    settings.reverb = { ...settings.reverb, mix: 0 };
    settings.delay = { ...settings.delay, mix: 0 };
    settings.drone = { ...settings.drone, volume: 0 };
    const midis = [48, 55, 60, 67, 72], gap = 1.3, len = 0.9;
    const notes = midis.map((midi, i) => ({ t: 0.1 + i * gap, midi, vel: 0.8, length: len }));
    const marks = midis.map((midi, i) => ({ start: 0.1 + i * gap, end: 0.1 + i * gap + len, midi }));
    const out = [];
    for (const [id, inst] of Object.entries(INSTRUMENTS)) {
      const buf = await AudioEngine.renderNotesOffline({ settings, duration: 0.2 + midis.length * gap, notes, instrument: id, length: len, sampleRate: 44100 });
      const L = buf.getChannelData(0), R = buf.getChannelData(1);
      const mono = new Float32Array(L.length);
      for (let i = 0; i < mono.length; i++) mono[i] = (L[i] + R[i]) / 2;
      const vec = describeTimbre(mono, buf.sampleRate, marks);
      const chord = (inst.osc || []).some((o) => (o.semi || 0) % 12 !== 0);
      // how many octaves the instrument sounds above (+) or below (−) the note it is asked for
      const found = segmentNotes(await trackPitch({ numberOfChannels: 1, sampleRate: buf.sampleRate, getChannelData: () => mono }), { floorDb: 50 });
      const offs = marks.map((m) => { const f = found.find((n) => Math.abs(n.start - m.start) < 0.12); return f ? f.midi - m.midi : null; }).filter((v) => v != null);
      offs.sort((a, b) => a - b);
      const med = offs.length >= 3 ? offs[offs.length >> 1] : 0;
      const shift = Math.abs(med - Math.round(med / 12) * 12) < 0.6 ? Math.round(med / 12) * 12 : 0;
      if (vec) out.push({ id, vec: vec.map((v) => Math.round(v * 1000) / 1000), chord, shift });
    }
    return out;
  });
} finally {
  await browser.close();
  server.kill();
}
const text = `// Generated by scripts/build-fingerprints.mjs: the timbre fingerprint of every instrument.\n// Do not edit by hand.\nexport const FINGERPRINTS = ${JSON.stringify(rows)}.map(([id, vec, chord, shift]) => ({ id, vec, chord, shift }));\n`.replace(JSON.stringify(rows), JSON.stringify(rows.map((r) => [r.id, r.vec, r.chord, r.shift])));
if (process.argv.includes('--check')) {
  const old = await readFile(OUT, 'utf8').catch(() => '');
  if (old !== text) { console.error('src/analysis/fingerprints.js is out of date: run node scripts/build-fingerprints.mjs'); process.exit(1); }
  console.log(`fingerprints up to date (${rows.length} instruments)`);
} else {
  await writeFile(OUT, text);
  console.log(`wrote ${rows.length} fingerprints`);
}
